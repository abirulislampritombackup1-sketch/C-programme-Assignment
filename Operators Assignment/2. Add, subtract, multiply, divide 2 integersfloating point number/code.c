// C programme for add,subtraction, multiplication,division of two float

#include<stdio.h>
int main () {
    float a,b;
    printf("Enter two float numbers:");
    scanf("%f %f",&a,&b);
    printf("The sum of two float = %f \n",a+b);
    printf("The subtraction of two float = %f \n",a-b);
    printf("The multiplication of two float = %f \n",a*b);
    printf("The division of two float = %f \n",a/b);
    return 0;
}